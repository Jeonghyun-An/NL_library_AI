"""hangul.py — 조사 고르기

보고서에 코드가 이어 붙이는 말(한계 문장의 주어, note 의 논문 제목)은 앞말이 바뀌어도
조사가 맞아야 한다. 한계 섹션에 둘이 나란히 실려 한쪽만 틀려도 드러난다.
"""


def josa(word: str, pair: str) -> str:
    """word 뒤에 붙일 조사. pair 는 받침이 있을 때·없을 때 순서의 두 글자다('은는'·'이가'·'을를'·'과와').

    한글로 끝나지 않으면(영문·숫자·괄호) 읽는 소리를 코드가 알 수 없다 — 'HPC' 는 '는'(에이치피시)이지만
    'LAN' 은 '은'(랜)이다. 틀린 조사보다 '(은)는' 병기가 낫다.
    """
    last = word[-1:]
    if "가" <= last <= "힣":
        return pair[0] if (ord(last) - ord("가")) % 28 else pair[1]
    return f"({pair[0]}){pair[1]}"

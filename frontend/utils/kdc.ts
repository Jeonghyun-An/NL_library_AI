export interface KdcChip {
  /** 칩에 보이는 이름 */
  name: string;
  /** 앞 3자리(없으면 2자리) 분류 번호 */
  code: string;
  /** title·스크린리더용 — '도서관 분류(KDC 329)' */
  title: string;
}

/** '329' · '813.6' · ' 811.609 ' · 329 → 소수점 앞 정수부의 숫자. 못 읽으면 빈 문자열 */
function integerPart(kdc: string | number | null | undefined): string {
  if (kdc === null || kdc === undefined) return "";
  const text = String(kdc).trim();
  const m = text.match(/^\D*(\d+)/);
  return m?.[1] ?? "";
}

/**
 * KDC 값 → 분류 칩. 앞 3자리(요목)로 먼저 찾고, 없으면 앞 2자리(강목)로 대신하며, 둘 다 못 찾거나 값이 비었으면 null(칩 없음).
 * 소수점 아래(813.6 의 .6)와 앞뒤 공백은 이름을 정하는 데 쓰지 않는다
 */
export function kdcChip(kdc: string | number | null | undefined): KdcChip | null {
  const digits = integerPart(kdc);
  if (digits.length < 2) return null;
  const section = digits.slice(0, 3);
  const division = digits.slice(0, 2);
  const name = (section.length === 3 ? KDC_SECTIONS[section] : undefined) ?? KDC_DIVISIONS[division];
  if (!name) return null;
  const code = section.length === 3 ? section : division;
  return { name, code, title: `도서관 분류(KDC ${code})` };
}
